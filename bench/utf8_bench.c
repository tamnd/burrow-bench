/* ------------------------------------------------------------------ encoding */

BENCH(utf8_encode_ascii) {
    Byte buf[8];
    Slice out = slice_from(buf, (Int)sizeof buf, (Int)sizeof buf, TYPE_BYTE);

    BENCH_LOOP(b) {
        bench_keep_u64((uint64_t)utf8_encode_rune(out, (Rune)('a' + (bench_i_ & 15))));
    }
}

BENCH(utf8_encode_wide) {
    Byte buf[8];
    Slice out = slice_from(buf, (Int)sizeof buf, (Int)sizeof buf, TYPE_BYTE);

    BENCH_LOOP(b) {
        bench_keep_u64(
            (uint64_t)utf8_encode_rune(out, (Rune)(0x1F300 + (bench_i_ & 15))));
    }
}

BENCH(utf8_rune_len) {
    BENCH_LOOP(b) {
        bench_keep_u64((uint64_t)utf8_rune_len((Rune)(0x1F300 + (bench_i_ & 15))));
    }
}

